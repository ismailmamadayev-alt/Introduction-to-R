## Сюжет: мониторинг реки на 3 станциях (Upstream/Midstream/Downstream)
## в тёплый сезон (май–сентябрь). Переменные:
## - month: месяц
## - site: станция
## - temp: температура воды (°C)
## - nitrate: нитраты NO3 (мг/л)
## - turbidity: мутность (NTU)
## - algae: индекс «цветения» (0–10)

set.seed(1)  # чтобы у всех получались одинаковые числа

month <- rep(c("May","Jun","Jul","Aug","Sep"), times = 3)
site  <- rep(c("Upstream","Midstream","Downstream"), each = 5)

temp <- c(12, 14, 17, 16, 13) + rnorm(5, 0, 0.7)
temp <- rep(temp, times = 3) + c(rep(0,5), rep(1.0,5), rep(2.0,5))

nitrate <- c(1.8, 2.0, 2.6, 2.4, 2.1) + rnorm(5, 0, 0.25)
nitrate <- rep(nitrate, times = 3) + c(rep(0,5), rep(0.6,5), rep(1.2,5))

turbidity <- c(4, 5, 7, 6, 5) + rnorm(5, 0, 0.8)
turbidity <- rep(turbidity, times = 3) + c(rep(0,5), rep(1.5,5), rep(3.5,5))

algae <- pmin(10, pmax(0, 0.6*temp + 0.8*nitrate + rnorm(15, 0, 0.8) - 10))

river <- data.frame(
  month = month,
  site = site,
  temp = round(temp, 1),
  nitrate = round(nitrate, 2),
  turbidity = round(turbidity, 1),
  algae = round(algae, 1)
)

## Посмотрите на таблицу (это НЕ задание, просто знакомство с данными)
